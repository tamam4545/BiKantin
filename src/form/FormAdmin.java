    public void loadDataMenu() {
        modelMenu = new DefaultTableModel();
        modelMenu.addColumn("ID");
        modelMenu.addColumn("Nama Menu");
        modelMenu.addColumn("Harga");
        modelMenu.addColumn("Kategori");
        tblMenu.setModel(modelMenu);

        try {
            Connection c = Koneksi.configDB();
            Statement s = c.createStatement();
            ResultSet r = s.executeQuery("SELECT * FROM menu ORDER BY id ASC");
            while (r.next()) {
                modelMenu.addRow(new Object[]{
                    r.getInt("id"),
                    r.getString("nama_menu"),
                    r.getInt("harga"),
                    r.getString("kategori")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat menu: " + e.getMessage());
        }
    }

    public void loadDataPesanan() {
        modelPesanan = new DefaultTableModel();
        modelPesanan.addColumn("ID");
        modelPesanan.addColumn("Siswa");
        modelPesanan.addColumn("Menu");
        modelPesanan.addColumn("Jumlah");
        modelPesanan.addColumn("Total Harga");
        modelPesanan.addColumn("Status");
        tblPesanan.setModel(modelPesanan);

        try {
            Connection c = Koneksi.configDB();
            String sql = "SELECT p.id, u.username, m.nama_menu, p.jumlah, p.total_harga, p.status " +
                         "FROM pesanan p " +
                         "JOIN users u ON p.user_id = u.id " +
                         "JOIN menu m ON p.menu_id = m.id " +
                         "ORDER BY p.id DESC";
            Statement s = c.createStatement();
            ResultSet r = s.executeQuery(sql);
            while (r.next()) {
                modelPesanan.addRow(new Object[]{
                    r.getInt("id"),
                    r.getString("username"),
                    r.getString("nama_menu"),
                    r.getInt("jumlah"),
                    r.getInt("total_harga"),
                    r.getString("status")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat pesanan: " + e.getMessage());
        }
    }

