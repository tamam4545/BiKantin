    private void btnUbahStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahStatusActionPerformed
        int row = tblPesanan.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih salah satu pesanan siswa di tabel terlebih dahulu!");
            return;
        }

        String idPesanan = modelPesanan.getValueAt(row, 0).toString();
        String statusBaru = (String) cbStatusPesanan.getSelectedItem();

        try {
            Connection c = Koneksi.configDB();
            String sql = "UPDATE pesanan SET status = ? WHERE id = ?";
            PreparedStatement ps = c.prepareStatement(sql);
            ps.setString(1, statusBaru);
            ps.setInt(2, Integer.parseInt(idPesanan));
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Status pesanan #" + idPesanan + " berhasil diubah!");
            loadDataPesanan();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah status: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUbahStatusActionPerformed

