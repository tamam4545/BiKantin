    private void btnSimpanMenuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanMenuActionPerformed
        String nama = txtNamaMenu.getText().trim();
        String hargaStr = txtHarga.getText().trim();
        String kategori = (String) cbKategori.getSelectedItem();

        if (nama.isEmpty() || hargaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama menu dan harga harus diisi!");
            return;
        }

        try {
            int harga = Integer.parseInt(hargaStr);
            Connection c = Koneksi.configDB();
            String sql = "INSERT INTO menu (nama_menu, harga, kategori) VALUES (?, ?, ?)";
            PreparedStatement ps = c.prepareStatement(sql);
            ps.setString(1, nama);
            ps.setInt(2, harga);
            ps.setString(3, kategori);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Menu berhasil ditambahkan!");
            txtNamaMenu.setText("");
            txtHarga.setText("");
            cbKategori.setSelectedIndex(0);
            loadDataMenu();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga harus berupa angka!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menambah menu: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanMenuActionPerformed

    private void btnHapusMenuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusMenuActionPerformed
        int row = tblMenu.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih menu di tabel yang ingin dihapus!");
            return;
        }

        String idMenu = modelMenu.getValueAt(row, 0).toString();
        String namaMenu = modelMenu.getValueAt(row, 1).toString();

        int konfirmasi = JOptionPane.showConfirmDialog(this, 
                "Yakin ingin menghapus menu '" + namaMenu + "'?", 
                "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection c = Koneksi.configDB();
                String sql = "DELETE FROM menu WHERE id = ?";
                PreparedStatement ps = c.prepareStatement(sql);
                ps.setInt(1, Integer.parseInt(idMenu));
                ps.executeUpdate();

                JOptionPane.showMessageDialog(this, "Menu berhasil dihapus!");
                txtNamaMenu.setText("");
                txtHarga.setText("");
                loadDataMenu();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus menu: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusMenuActionPerformed

