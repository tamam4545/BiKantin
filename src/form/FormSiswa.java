    private void loadMenuComboBox() {
        cmbMenu.removeAllItems();
        mapHarga.clear();
        try {
            Connection c = Koneksi.configDB();
            Statement s = c.createStatement();
            ResultSet r = s.executeQuery("SELECT * FROM menu ORDER BY kategori ASC, nama_menu ASC");
            while (r.next()) {
                int id = r.getInt("id");
                String nama = r.getString("nama_menu");
                int harga = r.getInt("harga");
                String kategori = r.getString("kategori");

                mapHarga.put(id, harga);
                cmbMenu.addItem(id + " - " + nama + " [" + kategori + "] (Rp " + harga + ")");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat menu: " + e.getMessage());
        }
    }

    public void loadStatusDanRiwayatPesanan() {
        try {
            Connection c = Koneksi.configDB();

            // 1. Cek status pesanan terakhir
            String sqlLatest = "SELECT p.id, m.nama_menu, p.jumlah, p.total_harga, p.status " +
                               "FROM pesanan p " +
                               "JOIN menu m ON p.menu_id = m.id " +
                               "WHERE p.user_id = ? " +
                               "ORDER BY p.id DESC LIMIT 1";
            PreparedStatement ps = c.prepareStatement(sqlLatest);
            ps.setInt(1, idLoginSiswa);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String namaMenu = rs.getString("nama_menu");
                int qty = rs.getInt("jumlah");
                String status = rs.getString("status");
                lblStatusPesanan.setText("Status Pesanan Terkini: [" + status.toUpperCase() + "] (" + namaMenu + " x" + qty + ")");
            } else {
                lblStatusPesanan.setText("Status Pesanan: Belum ada pesanan");
            }

            // 2. Muat tabel riwayat pesanan siswa
            modelPesanan = new DefaultTableModel();
            modelPesanan.addColumn("ID");
            modelPesanan.addColumn("Menu");
            modelPesanan.addColumn("Jumlah");
            modelPesanan.addColumn("Total Harga");
            modelPesanan.addColumn("Status");
            tblPesanan.setModel(modelPesanan);

            String sqlAll = "SELECT p.id, m.nama_menu, p.jumlah, p.total_harga, p.status " +
                            "FROM pesanan p " +
                            "JOIN menu m ON p.menu_id = m.id " +
                            "WHERE p.user_id = ? " +
                            "ORDER BY p.id DESC";
            PreparedStatement psAll = c.prepareStatement(sqlAll);
            psAll.setInt(1, idLoginSiswa);
            ResultSet rsAll = psAll.executeQuery();
            while (rsAll.next()) {
                modelPesanan.addRow(new Object[]{
                    rsAll.getInt("id"),
                    rsAll.getString("nama_menu"),
                    rsAll.getInt("jumlah"),
                    rsAll.getInt("total_harga"),
                    rsAll.getString("status")
                });
            }
        } catch (Exception e) {
            lblStatusPesanan.setText("Status: Gagal memuat data");
        }
    }

