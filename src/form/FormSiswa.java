    private void btnPesanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesanActionPerformed
        if (cmbMenu.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Pilih menu terlebih dahulu!");
            return;
        }

        String selected = cmbMenu.getSelectedItem().toString();
        int idMenu = Integer.parseInt(selected.split(" - ")[0]);
        String qtyStr = txtJumlah.getText().trim();

        try {
            int jumlah = Integer.parseInt(qtyStr);
            if (jumlah <= 0) {
                JOptionPane.showMessageDialog(this, "Jumlah pesanan minimal 1!");
                return;
            }

            int hargaSatuan = mapHarga.getOrDefault(idMenu, 0);
            int totalHarga = hargaSatuan * jumlah;

            Connection c = Koneksi.configDB();
            String sql = "INSERT INTO pesanan (user_id, menu_id, jumlah, total_harga, status, status_pembayaran) " +
                         "VALUES (?, ?, ?, ?, 'Menunggu Konfirmasi', 'Belum Dibayar')";
            PreparedStatement ps = c.prepareStatement(sql);
            ps.setInt(1, idLoginSiswa);
            ps.setInt(2, idMenu);
            ps.setInt(3, jumlah);
            ps.setInt(4, totalHarga);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Pesanan berhasil dikirim ke kantin!");
            txtJumlah.setText("1");
            loadStatusDanRiwayatPesanan();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Jumlah harus berupa angka!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memesan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnPesanActionPerformed

